const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const toolkit = { features: {}, adapters: {} };
const context = vm.createContext({ window: { OperationsToolkit: toolkit }, console });
vm.runInContext(fs.readFileSync('libs/markdown-it.min.js', 'utf8'), context);
vm.runInContext(fs.readFileSync('libs/markdown-it-container.js', 'utf8'), context);
context.window.markdownit = context.markdownit;
context.window.markdownitContainer = context.markdownitContainer;
vm.runInContext(fs.readFileSync('scripts/features/markdown/renderer.js', 'utf8'), context);
const render = toolkit.features.markdown.toDescriptionHtml;
const source = '::: coupon\n券码：KEEP-ME\n:::\n## Product\n\n!!! danger Notice\nHandle carefully\n!!!';
const html = render(source);
assert(!html.includes('KEEP-ME'));
assert(html.includes('<h2>Product</h2>'));
assert(html.includes('admonition danger'));
assert(source.includes('KEEP-ME'));
assert.equal(render(''), '');
assert(!render('::: coupon\r\ncode\r\n:::\r\nBody').includes('code'));
assert.equal(render('::: coupon\nunclosed'), '');
assert(!render('::: coupon\na\n:::\nText\n::: coupon\nb\n:::').includes('coupon'));
console.log('Markdown HTML export checks passed');
